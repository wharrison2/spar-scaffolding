"""Apply near-duplicate and held-out-similarity thresholds to a combined prompt snapshot, producing the training prompt pool.

Input: a combined snapshot from combine_emergent_misalignment_prompt_corpus_batches.py (--input-snapshot). Local, free, no model call.
Similarity: the two lexical measures in lexical_prompt_similarity_measures.py (TF-IDF cosine on word 1-2 grams; Jaccard of
character 5-gram shingles), fitted on the snapshot's own prompts. Two prompts are near-duplicates when EITHER measure reaches its threshold.

1. Held-out contamination: any prompt whose similarity to any held-out prompt reaches the held-out thresholds is dropped
   (held-out prompts are read from <corpus folder>/held_out_set/held_out_set_*_prompts_*.jsonl; the run refuses if none exist or one is unreadable).
2. Near-duplicate clusters among the remaining prompts: walking the snapshot in file order (main corpus, then shares by number,
   first pass before second), a prompt is kept unless it reaches a threshold against an already kept prompt, in which case it is
   dropped and attributed to the first kept prompt it matched. So each cluster keeps exactly one prompt, the earliest in the file,
   and the choice is deterministic. (This leader rule, not connected components, stops chains of loosely similar prompts being collapsed.)

Default thresholds (all are flags). Chosen from data/emergent_misalignment_runs/prompt_similarity_problem_check_all_accepted_prompts_2026-11-11_13-30/
near_duplicate_lexical_similarity_2026-11-11_12-43/: across all 8.9M pairs of the 4,225 accepted prompts the maximum TF-IDF cosine was
0.253 and the maximum character-5-gram Jaccard 0.157, and hand reading of pairs ranked 1, 2, 4, 11, 60, 313, 700 and 1500 found none
that shared even a scenario (similarity there reflects shared language and template phrases). So the pool-internal defaults are
paraphrase-level: TF-IDF cosine 0.50 and Jaccard 0.40, well above anything that is merely same topic or language and well
below an exact or lightly edited copy (~1.0). They will normally drop nothing on current data; they exist as a guard for future
shares. Held-out defaults are stricter (cosine 0.40, Jaccard 0.30) since leaking a held-out scenario costs more than losing a
training prompt; the observed held-out-to-pool maxima are 0.177 and 0.148.

Output goes into the corpus's combined_snapshots/ folder beside the input snapshot (it is a derived snapshot of it), so a new
snapshot after more shares arrive is regenerated by rerunning with the new --input-snapshot. Files, named with the run time:
  near_duplicate_and_held_out_filtered_prompt_pool_<N>_prompts_<stamp>.jsonl
  near_duplicate_and_held_out_filter_report_<stamp>.json  (thresholds, counts, every dropped prompt with the prompt it
  duplicated or resembled and both similarities, input snapshot name and sha256)
The run is a single fast deterministic pass, so it is rerun in full rather than resumed.
"""

import argparse
import hashlib
import json
import sys
from datetime import datetime
from pathlib import Path

import numpy as np

SCRIPT_DIRECTORY = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIRECTORY))
from add_batch_to_emergent_misalignment_prompt_corpus import DEFAULT_CORPUS_FOLDER  # noqa: E402
from combine_emergent_misalignment_prompt_corpus_batches import (  # noqa: E402
    HELD_OUT_FILE_PATTERN, HELD_OUT_FOLDER_NAME, HeldOutSetUnreadable, TIMESTAMP_FORMAT)
from lexical_prompt_similarity_measures import (  # noqa: E402
    MEASURE_NAME_CHARACTER_FIVE_GRAM_JACCARD, MEASURE_NAME_TFIDF_COSINE, LexicalSimilarityModel, both_similarity_matrices)

DEFAULT_POOL_TFIDF_COSINE_THRESHOLD = 0.50
DEFAULT_POOL_CHARACTER_FIVE_GRAM_JACCARD_THRESHOLD = 0.40
DEFAULT_HELD_OUT_TFIDF_COSINE_THRESHOLD = 0.40
DEFAULT_HELD_OUT_CHARACTER_FIVE_GRAM_JACCARD_THRESHOLD = 0.30


def prompt_label(record: dict, position: int) -> str:
    return record.get("merged_corpus_prompt_id") or record.get("corpus_prompt_id") or f"line_{position + 1}"


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def read_held_out_records(corpus_folder: Path) -> tuple[list[dict], list[str]]:
    paths = sorted((Path(corpus_folder) / HELD_OUT_FOLDER_NAME).glob(HELD_OUT_FILE_PATTERN))
    if not paths:
        raise HeldOutSetUnreadable(f"no held-out set file in {Path(corpus_folder) / HELD_OUT_FOLDER_NAME}")
    records = []
    for path in paths:
        try:
            records += read_jsonl(path)
            [record["user_message"] for record in records]
        except (OSError, ValueError, KeyError, TypeError) as error:
            raise HeldOutSetUnreadable(f"cannot read held-out set file {path}: {error!r}") from error
    return records, [path.name for path in paths]


def filter_pool(pool: list[dict], held_out: list[dict], pool_thresholds: dict[str, float],
                held_out_thresholds: dict[str, float]) -> tuple[list[dict], list[dict], list[dict]]:
    """(kept records, dropped for held-out similarity, dropped as near-duplicates), each drop with its evidence."""
    texts = [record["user_message"] for record in pool]
    model = LexicalSimilarityModel(texts)
    labels = [prompt_label(record, position) for position, record in enumerate(pool)]
    held_out_drops, held_out_dropped_positions = [], set()
    if pool and held_out:
        held_out_texts = [record["user_message"] for record in held_out]
        against_held_out = both_similarity_matrices(model, texts, held_out_texts)
        for position in range(len(pool)):
            exceeded = {measure: float(matrix[position].max()) for measure, matrix in against_held_out.items()
                        if matrix[position].max() >= held_out_thresholds[measure]}
            if exceeded:
                best_measure = max(exceeded, key=exceeded.get)
                held_out_index = int(against_held_out[best_measure][position].argmax())
                held_out_dropped_positions.add(position)
                held_out_drops.append({
                    "dropped_prompt": labels[position], "dropped_user_message": texts[position],
                    "resembled_held_out_prompt": held_out[held_out_index].get("corpus_prompt_id"),
                    "resembled_held_out_user_message": held_out[held_out_index]["user_message"],
                    "triggering_measure": best_measure, "similarity": exceeded[best_measure],
                    "similarities": {measure: float(matrix[position, held_out_index]) for measure, matrix in against_held_out.items()}})
    within_pool = both_similarity_matrices(model, texts, texts) if pool else {}
    kept_positions, near_duplicate_drops = [], []
    for position in range(len(pool)):
        if position in held_out_dropped_positions:
            continue
        match = None
        for measure, matrix in within_pool.items():
            if not kept_positions:
                break
            row = matrix[position, kept_positions]
            best = int(row.argmax())
            if row[best] >= pool_thresholds[measure] and (match is None or kept_positions[best] < match[1]):
                match = (measure, kept_positions[best], float(row[best]))
        if match is None:
            kept_positions.append(position)
            continue
        measure, kept_position, similarity = match
        near_duplicate_drops.append({
            "dropped_prompt": labels[position], "dropped_user_message": texts[position],
            "duplicated_kept_prompt": labels[kept_position], "duplicated_kept_user_message": texts[kept_position],
            "triggering_measure": measure, "similarity": similarity,
            "similarities": {name: float(matrix[position, kept_position]) for name, matrix in within_pool.items()}})
    return [pool[position] for position in kept_positions], held_out_drops, near_duplicate_drops


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input-snapshot", type=Path, required=True, help="combined_prompt_corpus_<N>_prompts_<stamp>.jsonl")
    parser.add_argument("--corpus-folder", type=Path, default=DEFAULT_CORPUS_FOLDER,
                        help="holds held_out_set/ and receives the output in combined_snapshots/")
    parser.add_argument("--near-duplicate-tfidf-cosine-threshold", type=float, default=DEFAULT_POOL_TFIDF_COSINE_THRESHOLD)
    parser.add_argument("--near-duplicate-character-five-gram-jaccard-threshold", type=float,
                        default=DEFAULT_POOL_CHARACTER_FIVE_GRAM_JACCARD_THRESHOLD)
    parser.add_argument("--held-out-tfidf-cosine-threshold", type=float, default=DEFAULT_HELD_OUT_TFIDF_COSINE_THRESHOLD)
    parser.add_argument("--held-out-character-five-gram-jaccard-threshold", type=float,
                        default=DEFAULT_HELD_OUT_CHARACTER_FIVE_GRAM_JACCARD_THRESHOLD)
    arguments = parser.parse_args(argv)
    if "INCLUDES_HELD_OUT_PROMPTS_NOT_FOR_TRAINING" in arguments.input_snapshot.name:
        print("REFUSING TO RUN: the input snapshot is marked as including held-out prompts", file=sys.stderr)
        return 1
    try:
        held_out, held_out_files = read_held_out_records(arguments.corpus_folder)
    except HeldOutSetUnreadable as error:
        print(f"REFUSING TO RUN: {error}", file=sys.stderr)
        return 1
    pool = read_jsonl(arguments.input_snapshot)
    pool_thresholds = {MEASURE_NAME_TFIDF_COSINE: arguments.near_duplicate_tfidf_cosine_threshold,
                       MEASURE_NAME_CHARACTER_FIVE_GRAM_JACCARD: arguments.near_duplicate_character_five_gram_jaccard_threshold}
    held_out_thresholds = {MEASURE_NAME_TFIDF_COSINE: arguments.held_out_tfidf_cosine_threshold,
                           MEASURE_NAME_CHARACTER_FIVE_GRAM_JACCARD: arguments.held_out_character_five_gram_jaccard_threshold}
    kept, held_out_drops, near_duplicate_drops = filter_pool(pool, held_out, pool_thresholds, held_out_thresholds)
    output_folder = arguments.corpus_folder / "combined_snapshots"
    output_folder.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime(TIMESTAMP_FORMAT)
    prompts_path = output_folder / f"near_duplicate_and_held_out_filtered_prompt_pool_{len(kept)}_prompts_{stamp}.jsonl"
    prompts_path.write_text("".join(json.dumps(record, ensure_ascii=False) + "\n" for record in kept), encoding="utf-8")
    report = {
        "input_snapshot": str(arguments.input_snapshot),
        "input_snapshot_sha256": hashlib.sha256(arguments.input_snapshot.read_bytes()).hexdigest(),
        "output_prompt_pool_file": prompts_path.name, "held_out_set_files": held_out_files, "held_out_prompt_count": len(held_out),
        "near_duplicate_thresholds": pool_thresholds, "held_out_similarity_thresholds": held_out_thresholds,
        "counts": {"input_prompts": len(pool), "dropped_for_held_out_similarity": len(held_out_drops),
                   "dropped_as_near_duplicates": len(near_duplicate_drops), "final_pool": len(kept)},
        "dropped_for_held_out_similarity": held_out_drops, "dropped_as_near_duplicates": near_duplicate_drops}
    report_path = output_folder / f"near_duplicate_and_held_out_filter_report_{stamp}.json"
    report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(report["counts"], indent=2))
    print(f"Wrote {prompts_path}\nWrote {report_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
